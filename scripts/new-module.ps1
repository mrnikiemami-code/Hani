param(
    [Parameter(Mandatory = $true)]
    [ValidatePattern('^[A-Z][A-Za-z0-9]+$')]
    [string]$Name,

    [Parameter(Mandatory = $false)]
    [ValidatePattern('^[a-z][a-z0-9_]*$')]
    [string]$Schema = ""
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

if ([string]::IsNullOrWhiteSpace($Schema)) {
    $Schema = $Name.ToLowerInvariant()
}

$moduleRoot = Join-Path "src/Modules" $Name
if (Test-Path $moduleRoot) {
    throw "Module '$Name' already exists at '$moduleRoot'."
}

$projects = @(
    @{ Suffix = "Domain";         Ref = "src/Hani.BuildingBlocks/Hani.BuildingBlocks.Domain/Hani.BuildingBlocks.Domain.csproj" },
    @{ Suffix = "Application";    Ref = "src/Hani.BuildingBlocks/Hani.BuildingBlocks.Application/Hani.BuildingBlocks.Application.csproj" },
    @{ Suffix = "Infrastructure"; Ref = "src/Hani.BuildingBlocks/Hani.BuildingBlocks.Infrastructure/Hani.BuildingBlocks.Infrastructure.csproj" },
    @{ Suffix = "Presentation";   Ref = "src/Hani.BuildingBlocks/Hani.BuildingBlocks.AspNetCore/Hani.BuildingBlocks.AspNetCore.csproj" }
)

foreach ($project in $projects) {
    $projectName = "Hani.Modules.$Name.$($project.Suffix)"
    $projectPath = Join-Path $moduleRoot $projectName

    dotnet new classlib -n $projectName -o $projectPath -f net10.0 --no-restore | Out-Null
    Remove-Item (Join-Path $projectPath "Class1.cs") -Force -ErrorAction SilentlyContinue

    $csproj = Join-Path $projectPath "$projectName.csproj"
    dotnet add $csproj reference $project.Ref | Out-Null
}

# Intra-module references
dotnet add (Join-Path $moduleRoot "Hani.Modules.$Name.Application") reference `
    (Join-Path $moduleRoot "Hani.Modules.$Name.Domain") | Out-Null

dotnet add (Join-Path $moduleRoot "Hani.Modules.$Name.Infrastructure") reference `
    (Join-Path $moduleRoot "Hani.Modules.$Name.Application") | Out-Null

dotnet add (Join-Path $moduleRoot "Hani.Modules.$Name.Presentation") reference `
    (Join-Path $moduleRoot "Hani.Modules.$Name.Application") | Out-Null

Get-ChildItem -Path $moduleRoot -Recurse -Filter *.csproj | ForEach-Object {
    dotnet sln Hani.slnx add $_.FullName | Out-Null
}

$readme = @"
# Module: $Name

Schema: ``$Schema``

Structure is generated by ``scripts/new-module.ps1``. Add:

- ``Domain/{Aggregate}``
- ``Application/Commands/{UseCase}`` with Command + Handler + Validator
- ``Application/Queries/{UseCase}`` with Query + Handler + Validator
- ``Infrastructure/Persistence/{Module}DbContext``
- ``Presentation`` endpoints for Supplier / Channel / Marketplace
"@

Set-Content -Path (Join-Path $moduleRoot "README.md") -Value $readme -Encoding utf8

Write-Host "Module '$Name' created. Run scripts/verify.ps1."
